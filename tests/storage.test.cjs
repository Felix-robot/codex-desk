const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const TOML = require('@iarna/toml');
const { SettingsStore, normalizeSettings, inside } = require('../src/storage.cjs');

test('new installs use 6.1/high and explicit model choices survive restart', () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'desk-defaults-'));
  const encryption = { isEncryptionAvailable: () => false };
  const store = new SettingsStore(directory, encryption);
  assert.equal(store.settings.model, 'gpt-6.1-sol');
  assert.equal(store.settings.effort, 'high');
  store.writeConfig();
  const config = TOML.parse(fs.readFileSync(path.join(store.codexHome, 'config.toml'), 'utf8'));
  assert.equal(config.model, 'gpt-6.1-sol');
  assert.equal(config.model_reasoning_effort, 'high');
  store.save({ model: 'custom-provider-model', effort: 'low' });
  const reopened = new SettingsStore(directory, encryption);
  assert.equal(reopened.settings.model, 'custom-provider-model');
  assert.equal(reopened.settings.effort, 'low');
});

test('credentials stay out of settings and Codex config; isolated home survives restart', () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'desk-store-'));
  const encryption = { isEncryptionAvailable: () => true, encryptString: (s) => Buffer.from(s.split('').reverse().join('')), decryptString: (b) => b.toString().split('').reverse().join('') };
  const store = new SettingsStore(directory, encryption);
  store.save({ apiKey: 'test-only-secret', model: 'test-model' });
  store.writeConfig();
  const settings = fs.readFileSync(store.file, 'utf8');
  const config = fs.readFileSync(path.join(store.codexHome, 'config.toml'), 'utf8');
  assert.ok(!settings.includes('test-only-secret'));
  assert.ok(!config.includes('test-only-secret'));
  assert.equal(TOML.parse(config).model_providers.desk_api.env_key, 'CODEX_DESK_API_KEY');
  assert.deepEqual(TOML.parse(config).shell_environment_policy.exclude, ['CODEX_DESK_API_KEY']);
  assert.equal(new SettingsStore(directory, encryption).readKey(), 'test-only-secret');
  const projectDirectory = store.addProject(directory);
  store.renameProject(projectDirectory,'学习笔记');
  store.assignProject('owned-test-thread',projectDirectory);
  const restored = new SettingsStore(directory,encryption);
  assert.equal(restored.settings.projectNames[projectDirectory],'学习笔记');
  assert.equal(restored.settings.threadProjects['owned-test-thread'],projectDirectory);
  assert.equal(restored.settings.projects[0],projectDirectory);
  assert.ok(!Object.values(store.public()).includes('test-only-secret'));
  if (process.platform !== 'win32') assert.equal(fs.statSync(store.file).mode & 0o777, 0o600);
});
test('session-only credentials remove an older saved credential', () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'desk-session-'));
  const encryption = { isEncryptionAvailable: () => true, encryptString: (s) => Buffer.from(s), decryptString: (b) => b.toString() };
  const store = new SettingsStore(directory, encryption);
  store.save({ apiKey: 'old-key' });
  store.save({ apiKey: 'session-key', rememberKey: false });
  assert.equal(store.readKey(), 'session-key');
  assert.equal(fs.existsSync(store.secretFile), false);
  assert.equal(new SettingsStore(directory, encryption).readKey(), '');
});
test('existing relay key works across platforms only when enabled and survives restart', () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'desk-relay-'));
  const relayEnvFile = path.join(directory, 'relay.env');
  const contents = '# Existing local settings\r\nSUB2API_API_KEY=sk-test-only-relay\r\nOTHER_SETTING=test\r\n';
  fs.writeFileSync(relayEnvFile, contents);
  const encryption = { isEncryptionAvailable: () => false };
  const options = { relayEnvFile };
  const store = new SettingsStore(directory, encryption, options);
  assert.equal(store.readKey(), '');
  store.save({ useRelayEnv: true });
  store.writeConfig();
  const noKeychain = { isEncryptionAvailable: () => { throw new Error('Relay mode must not access the keychain'); } };
  const reopened = new SettingsStore(directory, noKeychain, options);
  assert.equal(reopened.readKey(), 'sk-test-only-relay');
  assert.equal(reopened.public().hasKey, true);
  assert.equal(reopened.public().keySource, 'relay-env');
  const config = TOML.parse(fs.readFileSync(path.join(store.codexHome, 'config.toml'), 'utf8'));
  assert.equal(config.model_provider, 'sub2api');
  assert.equal(config.model_providers.sub2api.env_key, 'SUB2API_API_KEY');
  assert.ok(!fs.readFileSync(store.file, 'utf8').includes('sk-test-only-relay'));
  assert.ok(!JSON.stringify(reopened.public()).includes('sk-test-only-relay'));
  assert.equal(fs.existsSync(store.secretFile), false);
  store.save({ clearKey: true });
  assert.equal(store.readKey(), '');
  assert.equal(fs.readFileSync(relayEnvFile, 'utf8'), contents);
});
test('path containment resolves symlinks and rejects siblings', () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'desk-path-'));
  const root = path.join(directory, 'project'); fs.mkdirSync(root);
  const outside = path.join(directory, 'outside'); fs.mkdirSync(outside);
  const file = path.join(root, 'a.txt'); fs.writeFileSync(file, 'ok');
  fs.symlinkSync(outside, path.join(root, 'escape'), process.platform === 'win32' ? 'junction' : 'dir');
  assert.equal(inside(root, file), true);
  assert.equal(inside(root, path.join(root, 'escape')), false);
  assert.throws(() => normalizeSettings({ baseUrl: 'file:///tmp' }));
});
